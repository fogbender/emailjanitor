defmodule EmailJanitor.Setup do
  @moduledoc "Local AWS self-host setup. Never enables workers, requests OAuth consent or applies infrastructure."
  alias EmailJanitor.{Address, Google, Mail, SelfHost}

  @doc "Create a new private setup directory. Existing directories and key material are never overwritten."
  def init(directory, owner, public_url) do
    safe(fn ->
      directory = Path.expand(directory)

      with true <- safe_path?(directory),
           {:ok, owner} <- Address.normalize(owner),
           :ok <- File.mkdir_p(Path.dirname(directory)),
           :ok <- File.mkdir(directory) do
        result =
          with :ok <- File.chmod(directory, 0o700),
               :ok <-
                 private_write(
                   Path.join(directory, "credential-key"),
                   :crypto.strong_rand_bytes(32)
                 ),
               :ok <-
                 private_write(
                   Path.join(directory, "web-secret"),
                   Base.encode64(:crypto.strong_rand_bytes(64))
                 ),
               env = settings(directory, owner, public_url),
               {:ok, config} <- SelfHost.Config.load(env),
               env = Map.put(env, "JANITOR_PUBLIC_URL", config.public_url),
               :ok <-
                 private_write(
                   Path.join(directory, "settings.json"),
                   Jason.encode!(env, pretty: true) <> "\n"
                 ),
               :ok <- private_write(Path.join(directory, ".gitignore"), "*\n!.gitignore\n") do
            {:ok, %{directory: directory, callback: config.public_url <> "/auth/google/callback"}}
          else
            _ -> {:error, :invalid_setup_configuration}
          end

        if match?({:error, _}, result), do: File.rm_rf(directory)
        result
      else
        {:error, :eexist} -> {:error, :setup_directory_exists}
        _ -> {:error, :invalid_setup_configuration}
      end
    end)
  end

  @doc "Read only metadata settings generated by init; secret values remain in runtime files."
  def load_settings(path) do
    safe(fn ->
      with {:ok, bytes} <- bounded_file(path, 32_768),
           {:ok, env} when is_map(env) <- Jason.decode(bytes),
           true <-
             map_size(env) <= 40 and
               Enum.all?(env, fn {key, value} ->
                 is_binary(key) and key in allowed_keys() and is_binary(value) and
                   byte_size(value) <= 4096 and not String.contains?(value, ["\n", "\r", <<0>>])
               end) do
        {:ok, env}
      else
        _ -> {:error, :invalid_setup_settings}
      end
    end)
  end

  @doc "Validate shared runtime settings and local readiness. Cloud capabilities and mailbox consent are never implied."
  def doctor(env, options \\ []) do
    safe(fn ->
      case SelfHost.Config.load(env) do
        {:ok, config} ->
          database = Keyword.get(options, :database_probe, &database_probe/1)

          checks = %{
            configuration: :ready,
            google_oauth: if(config.google_oauth, do: :ready, else: :not_configured),
            google_service_token: token_check(env["JANITOR_GOOGLE_TOKEN_FILE"]),
            gmail_notifications: notification_check(env),
            mail_transport: mail_check(env),
            database: if(database.(config.database) == :ok, do: :ready, else: :unavailable)
          }

          {:ok,
           %{
             checks: checks,
             local_ready: Enum.all?(checks, fn {_, value} -> value == :ready end),
             processing_ready: false,
             cloud_checks: :not_run
           }}

        _ ->
          {:ok,
           %{
             checks: %{configuration: :invalid_or_missing},
             local_ready: false,
             processing_ready: false,
             cloud_checks: :not_run
           }}
      end
    end)
  end

  @doc "Generate AWS IMDSv2 federation configuration through the official gcloud CLI only. No cloud apply or token exchange."
  def wif_config(provider, service_account, output, options \\ []) do
    safe(fn ->
      with true <- valid_provider?(provider),
           true <-
             is_binary(service_account) and
               Regex.match?(
                 ~r/\A[a-z][a-z0-9-]{4,28}[a-z0-9]@[a-z][a-z0-9-]{4,28}[a-z0-9]\.iam\.gserviceaccount\.com\z/,
                 service_account
               ),
           output = Path.expand(output),
           true <- safe_path?(output),
           false <- File.exists?(output),
           gcloud when is_binary(gcloud) <-
             Keyword.get_lazy(options, :gcloud, fn -> System.find_executable("gcloud") end) do
        directory = Path.join(System.tmp_dir!(), "emailjanitor-gcloud-" <> Ecto.UUID.generate())
        :ok = File.mkdir(directory)
        :ok = File.chmod(directory, 0o700)
        temporary = Path.join(directory, "external-account.json")
        runner = Keyword.get(options, :runner, &System.cmd/3)

        try do
          args = [
            "iam",
            "workload-identity-pools",
            "create-cred-config",
            provider,
            "--service-account=" <> service_account,
            "--aws",
            "--enable-imdsv2",
            "--output-file=" <> temporary,
            "--quiet"
          ]

          command_options = [
            stderr_to_stdout: true,
            env: [
              {"CLOUDSDK_CONFIG", directory},
              {"CLOUDSDK_CORE_DISABLE_PROMPTS", "1"},
              {"CLOUDSDK_CORE_LOG_HTTP", "false"}
            ]
          ]

          with {_, 0} <- runner.(gcloud, args, command_options),
               {:ok, bytes} <- bounded_file(temporary, 32_768),
               {:ok, value} <- Jason.decode(bytes),
               true <- valid_wif?(value, provider, service_account),
               :ok <- private_write(output, Jason.encode!(value, pretty: true) <> "\n") do
            {:ok, %{path: output}}
          else
            _ -> {:error, :gcloud_configuration_failed}
          end
        after
          File.rm_rf(directory)
        end
      else
        nil -> {:error, :gcloud_unavailable}
        _ -> {:error, :invalid_wif_configuration}
      end
    end)
  end

  defp settings(directory, owner, url),
    do: %{
      "JANITOR_ENABLE_SELF_HOST" => "0",
      "JANITOR_OWNER_EMAIL" => owner,
      "JANITOR_PUBLIC_URL" => url,
      "JANITOR_CREDENTIAL_KEY_FILE" => Path.join(directory, "credential-key"),
      "JANITOR_SECRET_KEY_BASE_FILE" => Path.join(directory, "web-secret"),
      "JANITOR_MODEL_PROVIDER" => "bedrock",
      "AWS_REGION" => "us-east-1"
    }

  defp allowed_keys,
    do:
      ~w(JANITOR_ENABLE_SELF_HOST JANITOR_OWNER_EMAIL JANITOR_PUBLIC_URL JANITOR_CREDENTIAL_KEY_FILE JANITOR_SECRET_KEY_BASE_FILE JANITOR_GOOGLE_CLIENT_JSON_FILE JANITOR_DATABASE_SOCKET JANITOR_DATABASE_NAME JANITOR_DATABASE_USER JANITOR_MODEL_PROVIDER JANITOR_MODEL_ID AWS_REGION JANITOR_ENABLE_SELF_HOST_WEB JANITOR_MAIL_SENDER JANITOR_MAIL_BUCKET JANITOR_MAIL_QUEUE_URL JANITOR_MAIL_TOPIC_ARN JANITOR_GOOGLE_PROJECT JANITOR_GOOGLE_TOPIC JANITOR_GOOGLE_SUBSCRIPTION JANITOR_GOOGLE_TOKEN_FILE)

  defp token_check(path),
    do: if(match?({:ok, _}, Google.ServiceToken.read(path)), do: :ready, else: :unavailable)

  defp notification_check(env) do
    topic = env["JANITOR_GOOGLE_TOPIC"]
    project = env["JANITOR_GOOGLE_PROJECT"]

    valid_topic =
      is_binary(project) and is_binary(topic) and
        String.starts_with?(topic, "projects/" <> project <> "/topics/") and
        Regex.match?(
          ~r/\Aprojects\/[a-z][a-z0-9-]{4,28}[a-z0-9]\/topics\/[A-Za-z][A-Za-z0-9_.~+%-]{2,254}\z/,
          topic
        )

    valid_subscription =
      match?(
        {:ok, _},
        Google.PubSub.Config.new(env["JANITOR_GOOGLE_SUBSCRIPTION"], fn -> {:error, :not_used} end)
      )

    if valid_topic and valid_subscription, do: :ready, else: :not_configured
  end

  defp mail_check(env) do
    result =
      Mail.Config.new(
        region: "us-east-1",
        sender: env["JANITOR_MAIL_SENDER"],
        bucket: env["JANITOR_MAIL_BUCKET"],
        queue_url: env["JANITOR_MAIL_QUEUE_URL"],
        topic_arn: env["JANITOR_MAIL_TOPIC_ARN"],
        credentials: fn -> {:error, :not_used} end
      )

    if match?({:ok, _}, result), do: :ready, else: :not_configured
  end

  defp database_probe(options) do
    with {:ok, _} <- Application.ensure_all_started(:postgrex),
         {:ok, pid} <-
           Postgrex.start_link(
             Keyword.merge(Keyword.delete(options, :log),
               backoff_type: :stop,
               connect_timeout: 1000,
               timeout: 1000
             )
           ) do
      try do
        case Postgrex.query(pid, "SELECT 1", [], timeout: 1000) do
          {:ok, %Postgrex.Result{rows: [[1]]}} -> :ok
          _ -> :error
        end
      after
        GenServer.stop(pid)
      end
    else
      _ -> :error
    end
  end

  defp valid_provider?(provider),
    do:
      is_binary(provider) and
        Regex.match?(
          ~r/\Aprojects\/[0-9]{1,30}\/locations\/global\/workloadIdentityPools\/[a-z][a-z0-9-]{2,30}[a-z0-9]\/providers\/[a-z][a-z0-9-]{2,30}[a-z0-9]\z/,
          provider
        )

  defp valid_wif?(value, provider, service_account) when is_map(value) do
    source = value["credential_source"]

    value["type"] == "external_account" and
      value["audience"] == "//iam.googleapis.com/" <> provider and
      value["subject_token_type"] == "urn:ietf:params:aws:token-type:aws4_request" and
      value["token_url"] == "https://sts.googleapis.com/v1/token" and
      value["service_account_impersonation_url"] ==
        "https://iamcredentials.googleapis.com/v1/projects/-/serviceAccounts/" <>
          service_account <> ":generateAccessToken" and
      is_map(source) and source["environment_id"] == "aws1" and
      source["imdsv2_session_token_url"] == "http://169.254.169.254/latest/api/token"
  end

  defp valid_wif?(_, _, _), do: false

  defp safe_path?(path),
    do:
      is_binary(path) and Path.type(path) == :absolute and
        not String.starts_with?(path, "/nix/store/") and
        not String.contains?(path, ["\n", "\r", <<0>>])

  defp bounded_file(path, limit) do
    with {:ok, %{type: :regular, size: size}} when size <= limit <- File.lstat(path),
         {:ok, bytes} <- File.open(path, [:read, :binary], &IO.binread(&1, limit + 1)),
         true <- is_binary(bytes) and byte_size(bytes) <= limit do
      {:ok, bytes}
    else
      _ -> {:error, :invalid_setup_file}
    end
  end

  defp private_write(path, bytes) do
    case File.open(path, [:write, :exclusive, :binary], fn file -> IO.binwrite(file, bytes) end) do
      {:ok, :ok} -> File.chmod(path, 0o600)
      _ -> {:error, :setup_write_failed}
    end
  end

  defp safe(fun) do
    fun.()
  rescue
    _ -> {:error, :setup_failed}
  catch
    _, _ -> {:error, :setup_failed}
  end
end
